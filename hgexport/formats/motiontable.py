def looping_ids(lookup: list[tuple[int, int]]) -> set[int] | None:
    """The resource ids that loop for a model with this motion-bank lookup,
    or None when no known table covers it."""
    ids = tuple(r for r, _e in lookup)
    for _name, _addr, rows, loops in TABLES:
        if ids and rows[:len(ids)] == ids:
            # the game finds a row by the first lookup row with that id (0x1F4710)
            return {ids[i] for i in loops if i < len(ids) and ids.index(ids[i]) == i}
    return None
